// Zuletzt verwendete Sprache, damit die Seite schon vor dem Laden der Einstellungen richtig erscheint.
const LANG_CACHE_KEY = 'weltzeit-lang';
let LANG = DEFAULT_LANG;
let LOCALE = 'de-DE';

function setLanguage(code) {
  LANG = validLang(code);
  LOCALE = LANGUAGES.find(l => l.code === LANG).locale;
  document.documentElement.lang = LANG;
  try { localStorage.setItem(LANG_CACHE_KEY, LANG); } catch { /* egal */ }
}

(function applyCachedLanguage() {
  let cached = null;
  try { cached = localStorage.getItem(LANG_CACHE_KEY); } catch { /* egal */ }
  setLanguage(cached);
})();

// Übersetzter Text; {name}-Platzhalter werden aus params ersetzt. Fehlt ein Schlüssel,
// wird auf Deutsch zurückgegriffen.
function tr(key, params) {
  const s = STRINGS[LANG][key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  if (!params || typeof s !== 'string') return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

// Zahl mit fester Nachkommazahl im Format der Sprache (z. B. 4,5 bzw. 4.5).
const numFmtCache = new Map();
function formatNumber(v, digits = 0) {
  const key = LOCALE + digits;
  if (!numFmtCache.has(key)) {
    numFmtCache.set(key, new Intl.NumberFormat(LOCALE, {
      minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false,
    }));
  }
  return numFmtCache.get(key).format(v);
}

// Setzt alle statischen Texte der Seite:
//   data-i18n="key"        → Textinhalt
//   data-i18n-html="key"   → HTML-Inhalt (nur eigene Texte mit Links)
//   data-i18n-attr="title:key; aria-label:key" → Attribute
function applyI18n(root = document) {
  for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = tr(e.dataset.i18n);
  for (const e of root.querySelectorAll('[data-i18n-html]')) e.innerHTML = tr(e.dataset.i18nHtml, I18N_LINKS);
  for (const e of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of e.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && key) e.setAttribute(attr, tr(key));
    }
  }
}
